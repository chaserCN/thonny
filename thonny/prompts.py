# Default language if requested language is not available
DEFAULT_LANGUAGE = "uk"


def get_prompt(prompt_type: PromptType, language: str = "uk", **kwargs) -> str:
    """
    Get a prompt by type and language.
    
    Args:
        prompt_type: Type of prompt to retrieve
        language: Language code (e.g., 'en', 'ru', 'uk')
        **kwargs: Additional parameters for string formatting (e.g., line_num, line_content)
    
    Returns:
        Formatted prompt string in the requested language.
        Falls back to Ukrainian if the requested language is not available.
    
    Example:
        >>> prompt = get_prompt(PromptType.SYSTEM_NORMAL, "ru")
        >>> print(prompt)
        Ты - полезный помощник по программированию...
        
        >>> prompt = get_prompt(
        ...     PromptType.AUTO_DEBUG_DISPLAY_WITH_LINE,
        ...     "ru",
        ...     line_num=10
        ... )
        >>> print(prompt)
        [auto] Что выполнится на строке 10?
    """
    if prompt_type not in PROMPTS:
        raise ValueError(f"Unknown prompt type: {prompt_type}")
    
    language_prompts = PROMPTS[prompt_type]
    
    # Try to get the prompt in the requested language, fall back to default
    if language in language_prompts:
        prompt_template = language_prompts[language]
    elif DEFAULT_LANGUAGE in language_prompts:
        prompt_template = language_prompts[DEFAULT_LANGUAGE]
    else:
        # If even default language is not available, use the first available
        prompt_template = next(iter(language_prompts.values()))
    
    # Remove leading newline if present (for better code formatting)
    if prompt_template.startswith('\n'):
        prompt_template = prompt_template[1:]
    
    # Format the prompt with provided kwargs if any
    if kwargs:
        try:
            return prompt_template.format(**kwargs)
        except KeyError as e:
            raise ValueError(f"Missing required parameter for prompt formatting: {e}")
    
    return prompt_template
